"""Builds data/search-index.js: one small list of everything a student might search for
(games, labs, practice topics and every card inside every game), used by engine/search.js.
Run automatically by tools-bump-version.py. Needs node."""
import json, pathlib, subprocess, re

ROOT = pathlib.Path(__file__).parent

def js_eval(code, *args):
    return json.loads(subprocess.check_output(["node", "-e", code, *map(str, args)]))

CAT = js_eval("const fs=require('fs');global.window={};eval(fs.readFileSync(process.argv[1],'utf8'));console.log(JSON.stringify(window.BGX_CATALOG))", ROOT / "data/catalog.js")
GAME = "const fs=require('fs');let G;global.BGX={registerGame:g=>G=g};eval(fs.readFileSync(process.argv[1],'utf8'));console.log(JSON.stringify(G))"

def short(t, n=70):
    t = re.sub(r"\s+", " ", str(t or "")).strip()
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "…"

out = []   # [type, name, subject id, detail line, url, extra keywords, (cards) words from the card's text]
STOP = set("this that with from have they their there these those which what when where while about into than then them also more most some such only over very your will been were being because between after before under other each both does doing done like just make made many much most must need needs used uses using usually often every".split())
for s in CAT["subjects"]:
    for lab in s.get("labs", []):
        if lab.get("status") == "live":
            out.append(["lab", lab["title"], s["id"], short(lab.get("text", ""), 90), lab["url"], f"lab simulation ch {lab.get('ch','')}"])
    for c in s["chapters"]:
        if c.get("status") != "live" or not c.get("url"): continue
        m = re.search(r"games/([^/]+)/", c["url"])
        if not m or not (ROOT / "data" / f"{m.group(1)}.js").exists(): continue
        gid = m.group(1)
        G = js_eval(GAME, ROOT / "data" / f"{gid}.js")
        cats = " ".join(x["name"] for x in G.get("categories", []))
        modes = " ".join(x.get("title", "") for x in G.get("modes", []))
        out.append(["game", G["title"], s["id"], f"{c.get('label') or ('Ch. ' + c['ch'] if str(c['ch'])[:1].isdigit() else c['ch'])} · {c['title']}", c["url"],
                    f"{G.get('tagline','')} {c['title']} {cats} {modes} chapter {c['ch']}"])
        exp = next((x["id"] for x in G.get("modes", []) if x.get("format") == "explorer"), None)
        base = c["url"] + (f"?mode={exp}" if exp else "")
        for it in G["items"]:
            detail = next((it[k] for k in ("job", "use", "where", "cls", "lack", "formula", "summary") if it.get(k)), "")
            extra = " ".join(str(it[k]) for k in ("symbol", "code", "cls", "eq") if it.get(k))
            body = " ".join([str(it.get("summary", ""))] + [str(x) for x in (it.get("facts") or [])] + [str(it.get(k, "")) for k in ("life", "job", "use", "where", "lack", "foods") if it.get(k)])
            seen = set(re.findall(r"[a-z0-9]+", (it["name"] + " " + str(detail)).lower()))
            words = []
            for w in re.findall(r"[A-Za-z][A-Za-z0-9\-]+", body):
                lw = w.lower()
                if len(lw) >= 4 and lw not in STOP and lw not in seen: seen.add(lw); words.append(lw)
            out.append(["card", it["name"], s["id"], short(detail), base, f"{G['title']} {extra}", " ".join(words[:45])])

pp = ROOT / "tools-practice-pages.py"
if pp.exists():
    ns = {"__name__": "practice", "__file__": str(pp)}
    exec(compile(pp.read_text(), str(pp), "exec"), ns)
    sid = {"Chemistry": "chemistry", "Anatomy & Physiology": "anatomy", "Pharmacology": "pharmacology", "Nutrition": "nutrition", "Health & Wellness": "wellness"}
    for p in ns["PAGES"]:
        out.append(["topic", p["h1"], sid.get(p["subject"], ""), p.get("short", ""), f"practice/{p['slug']}/index.html", p["title"]])

subjects = {s["id"]: [s["name"], s["color"]] for s in CAT["subjects"]}
(ROOT / "data" / "search-index.js").write_text(
    "/* generated by tools-search-index.py: do not edit by hand */\nwindow.BGX_SEARCH = " +
    json.dumps({"subjects": subjects, "items": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"search index: {len(out)} entries, {(ROOT / 'data' / 'search-index.js').stat().st_size // 1024} KB")
