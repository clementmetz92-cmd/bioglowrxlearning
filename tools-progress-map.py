"""Builds data/progress-map.js: for every game in data/catalog.js, its scored modes and round sizes.
The hub, subject pages and trophy cabinet read it to work out game, chapter and subject progress
without loading every game's data. Run after adding or changing a game's modes (tools-bump-version.py runs it too):
    python3 tools-progress-map.py
Needs Python Playwright with Chromium."""
import json, pathlib, re, sys
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).parent
cat = (ROOT / "data/catalog.js").read_text()
ids = sorted(set(re.findall(r'url:\s*"games/([a-z0-9-]+)/index\.html"', cat)))
games = {}
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page()
    for gid in ids:
        f = ROOT / "games" / gid / "index.html"
        if not f.exists(): continue
        pg.goto(f.resolve().as_uri())
        info = pg.evaluate("() => window.BGX && BGX.progressInfo ? BGX.progressInfo() : null")
        if info and info["modes"]: games[gid] = info          # labs have no scored modes: skipped
    b.close()
out = ("/* Generated by tools-progress-map.py: do not edit by hand.\n"
       "   Each game: its scored modes (id, title) and the round size per practice set (tot), used to read old best scores. */\n"
       "window.BGX_PROGRESS_MAP = " + json.dumps(games, ensure_ascii=False, separators=(",", ":")) + ";\n")
(ROOT / "data/progress-map.js").write_text(out)
print(f"progress map: {len(games)} games, {sum(len(g['modes']) for g in games.values())} scored modes")
